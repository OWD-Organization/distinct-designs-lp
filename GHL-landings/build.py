#!/usr/bin/env python3
"""Build single-file HTML pages for GoHighLevel.

GHL pages are pasted in as one block of HTML, so each output file carries its
own CSS and JS inline and references no sibling files.

This does not build the website. The site itself stays a no-build static
project; this only produces the handoff copies, so re-run it whenever a source
page changes:

    python3 GHL-landings/build.py

Add a page by appending to PAGES below.
"""

import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Images are not embedded. The set weighs roughly 1.8 MB and base64 would push
# each file past a comfortable size to paste into GHL, so they are served from
# the deployed site instead.
IMAGE_BASE = "https://distinct-designs-construction.vercel.app/custom-home-build/images/"

# (source page folder, output folder, output filename, label for the header)
PAGES = [
    ("custom-home-build", "custom-home-build",
     "custom-home-build.html", ""),
    ("custom-home-build-hero-form", "custom-home-build",
     "custom-home-build-hero-form.html", ", hero-form variant"),
]

HEADER = """<!--
  Distinct Designs Construction{label}
  Single-file build for GoHighLevel: CSS and JS are inlined, so this page needs
  no other files.

  IMAGES are absolute URLs pointing at
  {base}
  They are not embedded, because the set weighs about 1.8 MB and base64 would
  make this file too large to paste comfortably. To serve them from GHL instead,
  upload the files to the GHL media library and replace that base URL throughout.

  The Feedbucket review widget is stripped out by the build; it is a staging tool
  and should not run in front of prospects. The WhatConverts tags are kept.

  The lead form POSTs JSON to a GoHighLevel inbound webhook. The URL is the
  LEAD_WEBHOOK_URL constant in the script at the bottom of this file.

  CHECK THAT URL BEFORE LAUNCH. The endpoint replies
  {{"status":"Success: test request received"}} with HTTP 200 for any id, even
  one that does not exist, so a success response proves nothing. The only
  real verification is that a test submission shows up as a contact in GHL.

  Each payload carries "page" and "variant", so one webhook can receive all
  six pages and the workflow can branch on those fields.

  Generated by GHL-landings/build.py. Edit the source page, not this file.
-->
"""


def build(src_dir, out_dir, out_name, label):
    src = os.path.join(REPO, src_dir)
    html = open(os.path.join(src, "index.html"), encoding="utf-8").read()
    css = open(os.path.join(src, "styles.css"), encoding="utf-8").read()
    js = open(os.path.join(src, "script.js"), encoding="utf-8").read()

    # Inlining would break the document if a payload closed its own tag.
    assert "</style>" not in css.lower(), f"{src_dir}: css contains </style>"
    assert "</script>" not in js.lower(), f"{src_dir}: js contains </script>"

    link = '<link rel="stylesheet" href="styles.css">'
    assert html.count(link) == 1, f"{src_dir}: stylesheet link not found once"
    html = html.replace(link, "<style>\n" + css.rstrip() + "\n</style>")

    tag = '<script src="script.js"></script>'
    assert html.count(tag) == 1, f"{src_dir}: script tag not found once"
    html = html.replace(tag, "<script>\n" + js.rstrip() + "\n</script>")

    fb = re.search(r"\n<!-- Feedbucket.*?</script>\n", html, re.S)
    assert fb, f"{src_dir}: Feedbucket block not found"
    html = html[: fb.start()] + "\n" + html[fb.end():]

    html = re.sub(r'(src|srcset)="images/', lambda m: f'{m.group(1)}="{IMAGE_BASE}', html)
    html = re.sub(r"(\d+w, )images/", lambda m: m.group(1) + IMAGE_BASE, html)
    stripped = html.replace(IMAGE_BASE, "")
    assert 'images/' not in stripped, f"{src_dir}: a relative image path survived"

    # The review widget must be gone; the header comment naming it is fine.
    body = html[html.index("<body"):]
    assert "feedbucket" not in body.lower(), f"{src_dir}: Feedbucket still in body"

    out = os.path.join(REPO, "GHL-landings", out_dir)
    os.makedirs(out, exist_ok=True)
    path = os.path.join(out, out_name)
    open(path, "w", encoding="utf-8").write(
        HEADER.format(label=label, base=IMAGE_BASE) + html)
    return path, os.path.getsize(path)


if __name__ == "__main__":
    for args in PAGES:
        path, size = build(*args)
        print(f"  {os.path.relpath(path, REPO)}  ({size / 1024:.0f} KB)")
